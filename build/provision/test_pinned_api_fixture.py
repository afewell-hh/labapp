"""Independent public-fixture checks for the VLAB API object comparison (#394).

Inputs are produced by build/provision/fixtures/pinned-api (real pinned
fabricator v0.43.1 printer/loader and fabric v0.96.2 typed Default) in a
separate lead-reviewed hosted step; LABAPP_PINNED_API_FIXTURE_DIR names the
directory holding expected.yaml, observed.json and meta.json. When it is unset
or incomplete every test FAILS (it never skips or passes empty), so a required
step cannot succeed without the generated fixture.

No network, kubectl, hhfab, Docker or credentials. This is NOT part of the
default test_vlab_core.py discovery. It exercises the real object_identity and
object_value and the same dictionary-equality rule as api_ready; it does not
call api_ready (its counts/kubectl/kubeconfig are not represented) and proves
neither live admission, OCI bytes, canonical11's diff nor VM functionality.
"""
import copy
import os
from pathlib import Path
import unittest

import vlab_core as core

PREFIX = 'fabric.githedgehog.com/'
LIMIT = 1 << 20


def read_fixture(name):
    root = os.environ.get('LABAPP_PINNED_API_FIXTURE_DIR')
    if not root:
        raise AssertionError('LABAPP_PINNED_API_FIXTURE_DIR is required; fixture not generated')
    path = Path(root) / name
    if not path.is_file() or path.is_symlink() or path.stat().st_size > LIMIT:
        raise AssertionError('required generated fixture missing or oversized: ' + name)
    return path.read_bytes()


def refuses(expected, observed):
    """The same rule api_ready applies after listing objects (vlab_core.py)."""
    expected_map = {core.object_identity(d): core.object_value(d) for d in expected}
    actual_map = {core.object_identity(d): core.object_value(d) for d in observed}
    return not (len(expected_map) == len(expected) and len(actual_map) == len(observed)
                and actual_map == expected_map)


def by_kind(docs, kind):
    found = [d for d in docs if d['kind'] == kind]
    assert len(found) == 1, kind
    return found[0]


class PinnedApiAsymmetry(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.expected = core.yaml_documents(read_fixture('expected.yaml'))
        cls.observed = core.json_data(read_fixture('observed.json'))
        cls.meta = core.json_data(read_fixture('meta.json'))

    def test_two_independent_sides_cover_public_kinds(self):
        for docs in (self.expected, self.observed):
            self.assertEqual(sorted(d['kind'] for d in docs), ['Connection', 'Server', 'Switch'])
        self.assertTrue(self.meta['typedDefaultInvoked']['Switch'])
        self.assertTrue(self.meta['typedDefaultInvoked']['Connection'])
        # Parsed independently, not one dict copied to both sides.
        self.assertIsNot(self.expected, self.observed)
        self.assertEqual({core.object_identity(d)[3] for d in self.expected},
                         {core.object_identity(d)[3] for d in self.observed})
        for doc in self.expected:
            meta = doc['metadata']
            self.assertFalse([k for k in meta.get('labels', {}) if PREFIX in k], doc['kind'])
            self.assertNotIn('kubectl.kubernetes.io/last-applied-configuration',
                             meta.get('annotations', {}))

    def test_current_comparison_refuses_predicted_difference(self):
        self.assertTrue(refuses(self.expected, self.observed))
        for kind in ('Switch', 'Connection'):
            exp, obs = by_kind(self.expected, kind), by_kind(self.observed, kind)
            self.assertEqual(core.object_identity(exp), core.object_identity(obs))
            self.assertNotEqual(core.object_value(exp), core.object_value(obs), kind)
            # Derived labels are stripped when printed and regenerated by Default.
            self.assertFalse([k for k in exp['metadata'].get('labels', {}) if PREFIX in k])
            self.assertTrue([k for k in obs['metadata'].get('labels', {}) if PREFIX in k])
            self.assertNotIn(PREFIX + 'stale', obs['metadata']['labels'])
        exp, obs = by_kind(self.expected, 'Switch'), by_kind(self.observed, 'Switch')
        # Unrelated metadata survives on both sides.
        for doc in (exp, obs):
            self.assertEqual(doc['metadata']['labels']['example.com/keep'], 'yes')
            self.assertEqual(doc['metadata']['annotations']['example.com/note'], 'keep-me')
        # Selected spec defaults/ordering exist only on the observed side.
        self.assertEqual(obs['spec']['groups'], ['alpha', 'pair-1', 'zeta'])
        self.assertEqual(obs['spec']['vlanNamespaces'], ['vlan-a', 'vlan-b'])
        self.assertEqual(obs['spec']['portGroupSpeeds'], {'1': '10G'})
        self.assertEqual(obs['spec']['portSpeeds'], {'E1/2': '25G'})
        self.assertNotEqual(exp['spec'], obs['spec'])
        # Identity-preserving control: Server has no spec/label asymmetry here.
        self.assertEqual(core.object_value(by_kind(self.expected, 'Server'))['spec'],
                         core.object_value(by_kind(self.observed, 'Server'))['spec'])

    def accepted(self):
        """A baseline the comparison accepts: observed vs an independent deep copy."""
        return copy.deepcopy(self.observed), copy.deepcopy(self.observed)

    def test_baseline_and_ignored_controls_are_accepted(self):
        expected, observed = self.accepted()
        self.assertFalse(refuses(expected, observed))
        # Namespace omission equals the default; status/server metadata ignored.
        sw = by_kind(observed, 'Switch')
        self.assertEqual(sw['metadata']['namespace'], 'default')
        del sw['metadata']['namespace']
        by_kind(observed, 'Server')['status'] = {'ordinary': 'status'}
        for doc in observed:
            doc['metadata'].update({'uid': 'u-1', 'resourceVersion': '9', 'generation': 3,
                                    'creationTimestamp': '2026-01-01T00:00:00Z',
                                    'managedFields': [{'manager': 'kubectl'}]})
        self.assertFalse(refuses(expected, observed))

    def test_negative_cases_refused(self):
        def drift(path_kind, mutate):
            expected, observed = self.accepted()
            mutate(by_kind(observed, path_kind))
            return refuses(expected, observed)
        cases = {
            'switch ip': ('Switch', lambda d: d['spec'].update(ip='172.30.0.9/21')),
            'switch asn': ('Switch', lambda d: d['spec'].update(asn=65102)),
            'switch profile': ('Switch', lambda d: d['spec'].update(profile='other')),
            'unknown spec field': ('Switch', lambda d: d['spec'].update(unknownField=True)),
            'unrelated label': ('Switch', lambda d: d['metadata']['labels'].update({'example.com/keep': 'no'})),
            'unrelated label added': ('Server', lambda d: d['metadata'].setdefault('labels', {}).update(x='y')),
            'annotation drift': ('Connection', lambda d: d['metadata']['annotations'].update(
                {'example.com/note': 'changed'})),
            'nested list order': ('Switch', lambda d: d['spec']['groups'].reverse()),
            'name drift': ('Server', lambda d: d['metadata'].update(name='server-02')),
            'namespace drift': ('Server', lambda d: d['metadata'].update(namespace='other')),
            'apiVersion drift': ('Connection', lambda d: d.update(apiVersion='wiring.githedgehog.com/v1alpha1')),
        }
        for name, (kind, mutate) in cases.items():
            with self.subTest(name):
                self.assertTrue(drift(kind, mutate))

    def test_duplicate_identities_refused(self):
        for side in (0, 1):
            with self.subTest(side=('expected', 'observed')[side]):
                pair = list(self.accepted())
                pair[side].append(copy.deepcopy(pair[side][0]))
                self.assertTrue(refuses(*pair))
        expected, observed = self.accepted()
        observed.append(copy.deepcopy(by_kind(observed, 'Server')))
        expected.append(copy.deepcopy(by_kind(expected, 'Server')))
        self.assertTrue(refuses(expected, observed))

    def test_typed_fixture_limits_are_explicit(self):
        # Unknown spec fields are injected into decoded JSON above: typed
        # Go unmarshaling drops them, so this fixture cannot produce one.
        self.assertNotIn('unknownField', by_kind(self.observed, 'Switch')['spec'])


if __name__ == '__main__':
    unittest.main()
